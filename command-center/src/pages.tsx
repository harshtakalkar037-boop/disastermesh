export function InboxPage() {
  const [q, setQ] = useState("");
  const [state, setState] = useState("");
  const [urgency, setUrgency] = useState("");
  const [verification, setVerification] = useState("");
  const [assigned, setAssigned] = useState("");
  const [sort, setSort] = useState("priority");
  const query = new URLSearchParams({ q, state, urgency, verification, assigned }).toString();
  const { data, error, loading, reload } = useApi<{ incidents: Incident[] }>(`/api/v1/incidents?${query}`);
  const [ackId, setAckId] = useState<string | null>(null);
  const rows = useMemo(() => {
    const list = [...(data?.incidents ?? [])];
    list.sort((a, b) => sort === "age" ? Number(b.event_timestamp) - Number(a.event_timestamp) : a.priority - b.priority);
    return list;
  }, [data, sort]);
  return (
    <section>
      <h1 className="mt-0">Incident inbox</h1>
      <div className="grid md:grid-cols-6 gap-2 mb-4">
        <input aria-label="Search" placeholder="Search" value={q} onChange={(e) => setQ(e.target.value)} />
        <select aria-label="State" value={state} onChange={(e) => setState(e.target.value)}><option value="">Any state</option><option value="need_help">Need help</option><option value="safe">Safe</option><option value="evacuating">Evacuating</option><option value="unknown">Unknown</option></select>
        <select aria-label="Urgency" value={urgency} onChange={(e) => setUrgency(e.target.value)}><option value="">Any urgency</option><option value="0">P0</option><option value="1">P1</option><option value="2">P2</option><option value="3">P3</option><option value="4">P4</option></select>
        <select aria-label="Verification" value={verification} onChange={(e) => setVerification(e.target.value)}><option value="">Any verification</option><option>unverified</option><option>eyewitness</option><option>corroborated</option><option>conflicting</option></select>
        <select aria-label="Assignment" value={assigned} onChange={(e) => setAssigned(e.target.value)}><option value="">Any assignment</option><option value="unassigned">Unassigned</option></select>
        <select aria-label="Sort" value={sort} onChange={(e) => setSort(e.target.value)}><option value="priority">Sort urgency</option><option value="age">Sort age</option></select>
      </div>
      <ErrorNote error={error} />
      {loading && <Skeleton />}
      {data && rows.length === 0 && <Empty title="Inbox is empty" body="No stored reports match these filters. Zeros are not hidden incidents." />}
      {rows.length > 0 && (
        <div className="panel overflow-auto">
          <table>
            <thead><tr><th>State</th><th>Type</th><th>People</th><th>Verification</th><th>Age</th><th>Auth</th><th></th></tr></thead>
            <tbody>
              {rows.map((row) => (
                <tr key={row.id}>
                  <td><StateChip state={row.emergency_state} /></td>
                  <td>{row.incident_type}<div className="text-mute">{row.summary_text}</div></td>
                  <td>{row.people_count ?? "—"}</td>
                  <td>{row.verification_level}</td>
                  <td>{age(row.event_timestamp)}{stale(row.event_timestamp) ? " · stale" : ""}</td>
                  <td>{row.source_auth}</td>
                  <td><button className="btn ghost" onClick={() => setAckId(row.id)}>Mark seen</button></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {ackId && (
        <Confirm
          title="Mark seen?"
          body="This records that an operator saw the report. It does not dispatch a team and it does not mean the person is safe."
          confirmLabel="Mark seen"
          onCancel={() => setAckId(null)}
          onConfirm={async () => {
            await api(`/api/v1/incidents/${encodeURIComponent(ackId)}/ack`, { method: "POST" });
            setAckId(null);
            reload();
          }}
        />
      )}
    </section>
  );
}

