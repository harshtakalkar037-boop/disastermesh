export function LoginPage() {
  const navigate = useNavigate();
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  async function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const data = new FormData(event.currentTarget);
    setPending(true);
    setError(null);
    try {
      const res = await api<{ token: string }>("/api/v1/auth/login", {
        method: "POST",
        body: JSON.stringify({ email: data.get("email"), password: data.get("password") }),
      });
      setToken(res.token);
      navigate("/");
    } catch (err) {
      setError(err instanceof Error ? err.message : "login failed");
    } finally {
      setPending(false);
    }
  }
  return (
    <div className="min-h-screen grid md:grid-cols-2">
      <section className="p-8 bg-[#1a1713] border-r border-line">
        <p className="tracking-[0.18em] text-hi font-bold">DISASTERMESH</p>
        <h1 className="text-5xl leading-none mt-4 mb-4">Command desk</h1>
        <p className="text-mute max-w-md">Operators see stored reports, not a promise that anyone has been rescued. Source authentication is not factual verification. Official warnings are never generated by the assistant.</p>
      </section>
      <section className="p-8">
        <h2>Operator sign in</h2>
        <form className="grid gap-3 max-w-md" onSubmit={onSubmit}>
          <label>Email<input name="email" type="email" autoComplete="username" required /></label>
          <label>Password<input name="password" type="password" autoComplete="current-password" required /></label>
          <ErrorNote error={error} />
          <button className="btn primary" disabled={pending}>{pending ? "Checking…" : "Enter desk"}</button>
        </form>
      </section>
    </div>
  );
}

